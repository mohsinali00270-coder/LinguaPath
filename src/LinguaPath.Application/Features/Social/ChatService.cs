            .FirstOrDefaultAsync(m => m.ConversationId == conversationId && m.UserId == userId && m.IsActive && !m.IsPending, ct);
        if (member is null || !member.Conversation.IsActive) return Error.NotFound("Chat");
        var restriction = await moderation.ChatRestrictionAsync(userId, ct);
        if (restriction is not null) return Error.Conflict(restriction.Code, restriction.Message);
        var now = clock.GetUtcNow();
        var cannot = await CannotSendAsync(userId, member, now, ct);
        if (cannot is not null && cannot.Code != "slow_mode") return cannot;

        var message = new Message
        {
            ConversationId = conversationId, SenderId = userId, Body = ModerationRules.Preview(text, 300), MessageType = MessageType.CompetitionCard,
            CompetitionId = competitionId, SentAt = now, ModerationStatus = MessageModeration.Clean, AiScannedAt = now
        };
        db.Messages.Add(message);
        await db.SaveChangesAsync(ct);
        var members = await MemberIdsAsync(conversationId, ct);
        foreach (var id in members)
            db.MessageRecipientStates.Add(new MessageRecipientState { MessageId = message.Id, UserId = id, DeliveredAt = id == userId ? now : null, SeenAt = id == userId ? now : null });
        member.Conversation.LastMessageId = message.Id;
        member.Conversation.LastMessageAt = now;
        await db.SaveChangesAsync(ct);

        var dto = (await ToDtosAsync(userId, [message.Id], ct))[0];
        try
        {
            await notifier.MessageAsync(members.Where(m => m != userId).ToList(), dto with { State = null }, ct);
            await notifier.MessageAsync([userId], dto, ct);
        }
        catch (Exception ex)
        {
            logger.LogDebug(ex, "Competition card broadcast failed");
        }
        return dto;
    }

