    public async Task<Result> LeaveAsync(Guid userId, int conversationId, CancellationToken ct = default)
    {
        var me = await db.ConversationMembers.Include(m => m.Conversation)
            .FirstOrDefaultAsync(m => m.ConversationId == conversationId && m.UserId == userId && m.IsActive, ct);
        if (me is null) return Error.NotFound("Chat");
        if (me.Conversation.Type == ConversationType.Direct)
        {
            // Leaving a direct chat = archive and clear it for me.
            me.IsArchived = true;
            me.ClearedBeforeMessageId = me.Conversation.LastMessageId ?? 0;
            await db.SaveChangesAsync(ct);
            return Result.Success();
        }

        var wasPending = me.IsPending;
        me.IsActive = false;
        me.IsPending = false;
        if (me.Role == MemberRole.Owner)
        {
            // FR-C24: the longest-serving admin (or member) becomes the owner; an empty group closes.
            var next = await db.ConversationMembers
                .Where(m => m.ConversationId == conversationId && m.UserId != userId && m.IsActive && !m.IsPending)
                .OrderByDescending(m => m.Role).ThenBy(m => m.JoinedAt).FirstOrDefaultAsync(ct);
            me.Role = MemberRole.Member;
            if (next is null) me.Conversation.IsActive = false;
            else next.Role = MemberRole.Owner;
            await db.SaveChangesAsync(ct);
            if (next is not null)
                await SystemMessageAsync(conversationId, $"{await NameAsync(userId, ct)} left. {await NameAsync(next.UserId, ct)} is now the owner", ct);
        }
        else
        {
            await db.SaveChangesAsync(ct);
            if (!wasPending) await SystemMessageAsync(conversationId, $"{await NameAsync(userId, ct)} left", ct);
        }
        await notifier.ConversationChangedAsync(await MemberIdsAsync(conversationId, ct), new ConversationChangedDto(conversationId, "members"), ct);
        return Result.Success();
    }

    public async Task<Result<MessageDto>> PostCompetitionCardAsync(Guid userId, int conversationId, int competitionId, string text,
        CancellationToken ct = default)
    {
