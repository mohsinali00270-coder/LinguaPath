    /// <summary>Why I can't send right now, or null (FR-C21 announcement mode, FR-C29 slow mode, direct-chat privacy and blocks).</summary>
    private async Task<Error?> CannotSendAsync(Guid userId, ConversationMember member, DateTimeOffset now, CancellationToken ct)
    {
        var c = member.Conversation;
        if (c.Type == ConversationType.Direct)
        {
            var otherId = await db.ConversationMembers.Where(m => m.ConversationId == c.Id && m.UserId != userId).Select(m => m.UserId).FirstAsync(ct);
            var allowed = await social.CanContactAsync(userId, otherId, false, ct);
            if (allowed.IsFailure)
                return allowed.Error!.Type == ErrorType.NotFound ? Error.Forbidden("cannot_message", "You can't message this learner.") : allowed.Error;
            return null;
        }
        // BR-32: under-18 learners chat with friends only, so not in public groups where anyone can join.
        if (c.IsPublic)
        {
            var dob = await db.Users.AsNoTracking().Where(u => u.Id == userId).Select(u => u.DateOfBirth).FirstOrDefaultAsync(ct);
            if (LinguaPath.Shared.AgeRules.IsMinor(dob, DateOnly.FromDateTime(now.UtcDateTime)))
                return Error.Forbidden("minor_friends_only", $"Learners under {LinguaPath.Shared.AgeRules.AdultAge} can only chat with friends, so they can't post in public groups.");
        }
        if (c.OnlyAdminsCanSend && member.Role == MemberRole.Member)
            return Error.Forbidden("announcement_only", "Only admins can send messages in this group.");
        var wait = ModerationRules.SlowModeWait(c.SlowModeSec, member.LastSentAt, now, member.Role);
        if (wait > 0) return Error.TooManyRequests("slow_mode", $"Slow mode is on. You can send again in {wait} seconds.");
        return null;
    }

    private async Task<string?> CannotSendReasonAsync(Guid userId, ConversationMember? member, CancellationToken ct)
    {
        if (member is null) return "Join the group to send messages.";
        var restriction = await moderation.ChatRestrictionAsync(userId, ct);
        if (restriction is not null) return restriction.Message;
        var error = await CannotSendAsync(userId, member, clock.GetUtcNow(), ct);
        return error?.Code == "slow_mode" ? null : error?.Message;
    }

    private async Task<Result<ConversationDto>> BuildAsync(Guid userId, int conversationId, CancellationToken ct)
    {
        var c = await db.Conversations.AsNoTracking().Include(x => x.Language).FirstOrDefaultAsync(x => x.Id == conversationId, ct);
        if (c is null) return Error.NotFound("Chat");
        var member = await db.ConversationMembers.Include(m => m.Conversation)
            .FirstOrDefaultAsync(m => m.ConversationId == conversationId && m.UserId == userId && m.IsActive && !m.IsPending, ct);
        var isAdmin = member?.Role is MemberRole.Admin or MemberRole.Owner;

        var rows = await db.ConversationMembers.AsNoTracking()
            .Where(m => m.ConversationId == conversationId && m.IsActive && (!m.IsPending || isAdmin))
            .OrderByDescending(m => m.Role).ThenBy(m => m.JoinedAt).Take(500)
            .Select(m => new { m.UserId, Name = m.User.DisplayName ?? m.User.FullName, m.User.PhotoUrl, m.User.IsBlocked, m.Role, m.IsPending, m.JoinedAt })
            .ToListAsync(ct);
        var ids = rows.Select(r => r.UserId).ToList();
        var hideOnline = (await db.UserPrivacySettings.AsNoTracking().Where(p => ids.Contains(p.UserId) && !p.ShowOnline)
            .Select(p => p.UserId).ToListAsync(ct)).ToHashSet();
        var members = rows.Select(r => new MemberDto(r.UserId, r.IsBlocked ? "Blocked account" : r.Name, r.IsBlocked ? null : r.PhotoUrl, r.Role,
            r.IsPending, r.JoinedAt, r.IsBlocked || hideOnline.Contains(r.UserId) ? null : presence.IsOnline(r.UserId))).ToList();

        var other = c.Type == ConversationType.Direct ? members.FirstOrDefault(m => m.UserId != userId) : null;
        var reason = await CannotSendReasonAsync(userId, member, ct);
        return new ConversationDto(c.Id, c.Type, c.Type == ConversationType.Direct ? other?.DisplayName ?? "Learner" : c.Name ?? "Group",
            c.Description, c.IconKey, other?.PhotoUrl, c.LanguageId, c.Language?.Name, c.IsPublic, c.OnlyAdminsCanSend, c.SlowModeSec,
            c.JoinApproval, member?.Role ?? MemberRole.Member, member?.IsMuted ?? false, member?.IsArchived ?? false,
            reason is null, reason, members, other?.UserId);
    }

    private async Task<IReadOnlyList<MessageDto>> ToDtosAsync(Guid userId, IReadOnlyList<long> ids, CancellationToken ct)
    {
        if (ids.Count == 0) return [];
        var rows = await db.Messages.AsNoTracking().Where(m => ids.Contains(m.Id))
            .Select(m => new
            {
                m.Id, m.ConversationId, m.SenderId, SenderName = m.Sender == null ? "" : m.Sender.DisplayName ?? m.Sender.FullName,
                SenderPhoto = m.Sender == null ? null : m.Sender.PhotoUrl, SenderBlocked = m.Sender != null && m.Sender.IsBlocked,
                m.Body, m.MessageType, m.ReplyToMessageId, m.SentAt, m.IsActive, m.ModerationStatus, m.Mentions, m.ClientId, m.CompetitionId
            })
            .ToListAsync(ct);

        var replyIds = rows.Where(r => r.ReplyToMessageId != null).Select(r => r.ReplyToMessageId!.Value).Distinct().ToList();
        var replies = await db.Messages.AsNoTracking().Where(m => replyIds.Contains(m.Id))
            .Select(m => new { m.Id, m.Body, m.IsActive, Name = m.Sender == null ? "" : m.Sender.DisplayName ?? m.Sender.FullName })
            .ToDictionaryAsync(m => m.Id, ct);
        var reactions = await db.MessageReactions.AsNoTracking().Where(r => ids.Contains(r.MessageId))
            .Select(r => new { r.MessageId, r.Emoji, r.UserId }).ToListAsync(ct);

        // My messages: Sent / Delivered / Seen across the other members (FR-C03).
        var myIds = rows.Where(r => r.SenderId == userId).Select(r => r.Id).ToList();
        var myReceipts = (await social.PrivacyAsync(userId, ct)).ReadReceipts;
        var hiddenReaders = db.UserPrivacySettings.Where(p => !p.ReadReceipts).Select(p => p.UserId);
        var states = myIds.Count == 0 ? []
            : await db.MessageRecipientStates.AsNoTracking().Where(s => myIds.Contains(s.MessageId) && s.UserId != userId)
                .Select(s => new { s.MessageId, Delivered = s.DeliveredAt != null, Seen = s.SeenAt != null && !hiddenReaders.Contains(s.UserId) })
                .ToListAsync(ct);

        return rows.Select(r =>
        {
            var deleted = !r.IsActive;
            DeliveryState? state = null;
            if (r.SenderId == userId)
            {
                var mine = states.Where(s => s.MessageId == r.Id).ToList();
                state = mine.Count == 0 ? DeliveryState.Sent
                    : myReceipts && mine.All(s => s.Seen) ? DeliveryState.Seen
                    : mine.All(s => s.Delivered) ? DeliveryState.Delivered
                    : DeliveryState.Sent;
            }
            ReplyPreviewDto? reply = null;
            if (r.ReplyToMessageId is { } rid && replies.TryGetValue(rid, out var rp))
                reply = new ReplyPreviewDto(rid, rp.Name, rp.IsActive ? ModerationRules.Preview(rp.Body, 100) : null, !rp.IsActive);
            var mentions = (r.Mentions ?? "").Split(',', StringSplitOptions.RemoveEmptyEntries)
                .Select(x => Guid.TryParse(x, out var g) ? g : Guid.Empty).Where(g => g != Guid.Empty).ToList();
            return new MessageDto(r.Id, r.ConversationId, r.SenderId,
                r.SenderBlocked ? "Blocked account" : r.SenderName, r.SenderBlocked ? null : r.SenderPhoto,
                // FR-C12: the text of deleted or removed messages never leaves the server.
                deleted ? null : r.Body, r.MessageType, reply, r.SentAt, deleted, r.ModerationStatus == MessageModeration.Masked, state,
                deleted ? [] : reactions.Where(x => x.MessageId == r.Id).GroupBy(x => x.Emoji)
                    .Select(g => new ReactionDto(g.Key, g.Count(), g.Select(x => x.UserId).ToList())).ToList(),
                mentions, r.SenderId == userId ? r.ClientId : null, r.CompetitionId);
        }).ToList();
    }

    private async Task SystemMessageAsync(int conversationId, string text, CancellationToken ct)
    {
        var now = clock.GetUtcNow();
        var message = new Message
        {
            ConversationId = conversationId, Body = ModerationRules.Preview(text, 300), MessageType = MessageType.System, SentAt = now,
            ModerationStatus = MessageModeration.Clean, AiScannedAt = now
        };
        db.Messages.Add(message);
        await db.SaveChangesAsync(ct);
        var c = await db.Conversations.FirstAsync(x => x.Id == conversationId, ct);
        c.LastMessageId = message.Id;
        c.LastMessageAt = now;
        await db.SaveChangesAsync(ct);
        try
        {
            var dto = (await ToDtosAsync(Guid.Empty, [message.Id], ct))[0];
            await notifier.MessageAsync(await MemberIdsAsync(conversationId, ct), dto, ct);
        }
        catch (Exception ex)
        {
            logger.LogDebug(ex, "System message broadcast failed");
        }
    }

    private async Task<string> NameAsync(Guid userId, CancellationToken ct) =>
        await db.Users.Where(u => u.Id == userId).Select(u => u.DisplayName ?? u.FullName).FirstOrDefaultAsync(ct) ?? "Someone";

    private static string? Icon(string? key) => key is not null && Icons.Contains(key) ? key : "chat";

    private static string Snippet(string body, string q)
    {
        var at = body.IndexOf(q, StringComparison.OrdinalIgnoreCase);
        if (at < 0 || body.Length <= 120) return ModerationRules.Preview(body, 120);
        var start = Math.Max(0, at - 40);
        var len = Math.Min(body.Length - start, 120);
        return (start > 0 ? "…" : "") + body.Substring(start, len) + (start + len < body.Length ? "…" : "");
    }
