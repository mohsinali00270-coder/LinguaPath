    public async Task<Result<ConversationDto>> JoinAsync(Guid userId, int conversationId, CancellationToken ct = default)
    {
        var c = await db.Conversations.FirstOrDefaultAsync(x => x.Id == conversationId && x.Type == ConversationType.Group && x.IsActive && x.IsPublic, ct);
        if (c is null) return Error.NotFound("Group");
        var restriction = await moderation.ChatRestrictionAsync(userId, ct);
        if (restriction is { Blocked: true }) return Error.Conflict(restriction.Code, restriction.Message);

        var row = await db.ConversationMembers.FirstOrDefaultAsync(m => m.ConversationId == conversationId && m.UserId == userId, ct);
        if (row is { IsActive: true, IsPending: false }) return await BuildAsync(userId, conversationId, ct);
        if (row is { IsActive: true, IsPending: true }) return Error.Conflict("join_pending", "Your request to join is waiting for an admin.");
        if (await FullAsync(conversationId, 1, ct) is { } full) return full;

        var now = clock.GetUtcNow();
        if (row is null)
        {
            row = new ConversationMember { ConversationId = conversationId, UserId = userId };
            db.ConversationMembers.Add(row);
        }
        row.IsActive = true;
        row.IsPending = c.JoinApproval;
        row.Role = MemberRole.Member;
        row.JoinedAt = now;
        row.LastReadMessageId = c.LastMessageId;
        await db.SaveChangesAsync(ct);

        if (c.JoinApproval)
        {
            await notifier.ConversationChangedAsync(await AdminIdsAsync(conversationId, ct), new ConversationChangedDto(conversationId, "join_request"), ct);
            return Error.Conflict("join_pending", "Request sent. An admin will approve it.");
        }
        await SystemMessageAsync(conversationId, $"{await NameAsync(userId, ct)} joined", ct);
        return await BuildAsync(userId, conversationId, ct);
    }

    public async Task<Result> AddMembersAsync(Guid userId, int conversationId, IReadOnlyList<Guid> memberIds, CancellationToken ct = default)
    {
        var me = await GroupAdminAsync(userId, conversationId, ct);
        if (me.IsFailure) return me.Error!;
        var ids = memberIds.Where(id => id != userId).Distinct().ToList();
        if (ids.Count == 0) return Error.Validation("UserIds", "Choose who to add.");
        foreach (var id in ids)
        {
            var ok = await social.CanContactAsync(userId, id, false, ct);
            if (ok.IsFailure) return Error.Validation("UserIds", ok.Error!.Message);
        }
        var existing = await db.ConversationMembers.Where(m => m.ConversationId == conversationId && ids.Contains(m.UserId)).ToListAsync(ct);
        var adding = ids.Where(id => !existing.Any(e => e.UserId == id && e.IsActive && !e.IsPending)).ToList();
        if (await FullAsync(conversationId, adding.Count(id => !existing.Any(e => e.UserId == id && e.IsActive)), ct) is { } full) return full;

        var now = clock.GetUtcNow();
        var lastId = await db.Conversations.Where(c => c.Id == conversationId).Select(c => c.LastMessageId).FirstAsync(ct);
        foreach (var id in adding)
        {
            var row = existing.FirstOrDefault(e => e.UserId == id);
            if (row is null)
            {
                row = new ConversationMember { ConversationId = conversationId, UserId = id };
                db.ConversationMembers.Add(row);
            }
            row.IsActive = true;
            row.IsPending = false;
            row.Role = MemberRole.Member;
            row.JoinedAt = now;
            row.LastReadMessageId = lastId;
        }
        await db.SaveChangesAsync(ct);

        var who = await NameAsync(userId, ct);
        var names = await db.Users.Where(u => adding.Contains(u.Id)).Select(u => u.DisplayName ?? u.FullName).ToListAsync(ct);
        if (names.Count > 0) await SystemMessageAsync(conversationId, $"{who} added {string.Join(", ", names)}", ct);
        await notifier.ConversationChangedAsync(await MemberIdsAsync(conversationId, ct), new ConversationChangedDto(conversationId, "members"), ct);
        return Result.Success();
    }

