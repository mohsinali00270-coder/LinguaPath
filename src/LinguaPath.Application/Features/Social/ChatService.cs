    public async Task<Result<SeenDto>> MarkSeenAsync(Guid userId, int conversationId, long upToMessageId, CancellationToken ct = default)
    {
        var member = await db.ConversationMembers.FirstOrDefaultAsync(m => m.ConversationId == conversationId && m.UserId == userId
                                                                           && m.IsActive && !m.IsPending, ct);
        if (member is null) return Error.NotFound("Chat");
        var now = clock.GetUtcNow();
        var upTo = await db.Messages.Where(m => m.ConversationId == conversationId && m.Id <= upToMessageId).MaxAsync(m => (long?)m.Id, ct) ?? 0;
        if (upTo == 0 || (member.LastReadMessageId ?? 0) >= upTo) return new SeenDto(conversationId, userId, member.LastReadMessageId ?? 0, now);

        member.LastReadMessageId = upTo;
        member.LastReadAt = now;
        await db.MessageRecipientStates
            .Where(s => s.UserId == userId && s.SeenAt == null && s.Message.ConversationId == conversationId && s.MessageId <= upTo)
            .ExecuteUpdateAsync(s => s.SetProperty(x => x.SeenAt, now).SetProperty(x => x.DeliveredAt, x => x.DeliveredAt ?? now), ct);
        await db.SaveChangesAsync(ct);

        var seen = new SeenDto(conversationId, userId, upTo, now);
        // FR-C03: with read receipts off, others don't learn that I've read it.
        var privacy = await social.PrivacyAsync(userId, ct);
        if (privacy.ReadReceipts)
            await notifier.SeenAsync((await MemberIdsAsync(conversationId, ct)).Where(id => id != userId).ToList(), seen, ct);
        return seen;
    }

