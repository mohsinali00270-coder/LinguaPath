    public async Task<Result<IReadOnlyList<MessageDto>>> MessagesAsync(Guid userId, int conversationId, long? before, int take, CancellationToken ct = default)
    {
        var member = await MemberAsync(userId, conversationId, ct);
        if (member is null) return Error.NotFound("Chat");
        take = Math.Clamp(take, 1, 100);

        var blockedByMe = db.UserBlocks.Where(b => b.BlockerId == userId).Select(b => b.BlockedId);
        var q = db.Messages.AsNoTracking().Where(m => m.ConversationId == conversationId && m.SentAt >= member.JoinedAt);
        if (member.ClearedBeforeMessageId is { } cleared) q = q.Where(m => m.Id > cleared);
        if (before is { } b) q = q.Where(m => m.Id < b);
        // FR-C10 "delete for me", and FR-S22: in groups I don't see learners I blocked.
        q = q.Where(m => !db.MessageRecipientStates.Any(s => s.MessageId == m.Id && s.UserId == userId && !s.IsActive));
        q = q.Where(m => m.SenderId == null || !blockedByMe.Contains(m.SenderId.Value));

        var page = await q.OrderByDescending(m => m.Id).Take(take).Select(m => m.Id).ToListAsync(ct);
        var dtos = await ToDtosAsync(userId, page, ct);
        return Result<IReadOnlyList<MessageDto>>.Success(dtos.OrderBy(m => m.Id).ToList());
    }

    public async Task<Result<MessageDto>> SendAsync(Guid userId, int conversationId, SendMessageRequest request, CancellationToken ct = default)
    {
        var text = (request.Text ?? "").Trim();
        var maxLength = await settings.GetIntAsync(SettingKeys.ChatMaxMessageLength, 1000, ct);
        if (text.Length == 0) return Error.Validation("Text", "Type a message.");
        if (text.Length > Math.Min(2000, maxLength)) return Error.Validation("Text", $"Messages can be up to {maxLength} characters.");

        var member = await db.ConversationMembers.Include(m => m.Conversation)
            .FirstOrDefaultAsync(m => m.ConversationId == conversationId && m.UserId == userId && m.IsActive && !m.IsPending, ct);
        if (member is null || !member.Conversation.IsActive) return Error.NotFound("Chat");
        var c = member.Conversation;

        // Repeated send of the same client message (retry after a dropped connection).
        if (!string.IsNullOrWhiteSpace(request.ClientId))
        {
            var dupe = await db.Messages.AsNoTracking().Where(m => m.ConversationId == conversationId && m.SenderId == userId
                                                                   && m.ClientId == request.ClientId).Select(m => (long?)m.Id).FirstOrDefaultAsync(ct);
            if (dupe is { } dupeId) return (await ToDtosAsync(userId, [dupeId], ct))[0];
        }

        var now = clock.GetUtcNow();
        var cannot = await CannotSendAsync(userId, member, now, ct);
        if (cannot is not null) return cannot;

        long? replyTo = null;
        if (request.ReplyToMessageId is { } rid)
        {
            if (!await db.Messages.AnyAsync(m => m.Id == rid && m.ConversationId == conversationId, ct))
                return Error.Validation("ReplyToMessageId", "That message isn't in this chat.");
            replyTo = rid;
        }

        var decision = await moderation.CheckMessageAsync(userId, conversationId, text, c.LanguageId, ct);
        if (!decision.Allowed) return decision.Error!;

        var members = await db.ConversationMembers.AsNoTracking()
            .Where(m => m.ConversationId == conversationId && m.IsActive && !m.IsPending)
            .Select(m => new { m.UserId, Name = m.User.DisplayName ?? m.User.FullName, m.IsMuted }).ToListAsync(ct);
        var mentions = c.Type == ConversationType.Group
            ? ModerationRules.Mentions(decision.Text, members.Where(m => m.UserId != userId).Select(m => (m.UserId, m.Name)))
            : [];

        var message = new Message
        {
            ConversationId = conversationId, SenderId = userId, Body = decision.Text, OriginalBody = decision.OriginalText,
            ReplyToMessageId = replyTo, MessageType = MessageType.Text, ClientId = request.ClientId?.Trim() is { Length: > 0 and <= 64 } cid ? cid : null,
            Mentions = mentions.Count == 0 ? null : string.Join(',', mentions), SentAt = now, ModerationStatus = decision.Status
        };
        db.Messages.Add(message);
        await db.SaveChangesAsync(ct);

        foreach (var m in members)
        {
            var mine = m.UserId == userId;
            var online = !mine && presence.IsOnline(m.UserId);
            db.MessageRecipientStates.Add(new MessageRecipientState
            {
                MessageId = message.Id, UserId = m.UserId, DeliveredAt = mine || online ? now : null, SeenAt = mine ? now : null
            });
        }
        c.LastMessageId = message.Id;
        c.LastMessageAt = now;
        member.LastSentAt = now;
        member.LastReadMessageId = message.Id;
        member.LastReadAt = now;
        // A new message brings an archived chat back for everyone (FR-C07).
        await db.ConversationMembers.Where(m => m.ConversationId == conversationId && m.IsArchived && m.UserId != userId)
            .ExecuteUpdateAsync(s => s.SetProperty(m => m.IsArchived, false), ct);
        await db.SaveChangesAsync(ct);

        if (decision.Status == MessageModeration.Pending) scans.Enqueue(message.Id);

        var mineDto = (await ToDtosAsync(userId, [message.Id], ct))[0];
        var others = members.Where(m => m.UserId != userId).Select(m => m.UserId).ToList();
        try
        {
            // Recipients get the same message without my delivery state.
            await notifier.MessageAsync(others, mineDto with { State = null }, ct);
            await notifier.MessageAsync([userId], mineDto, ct);

            var offline = members.Where(m => m.UserId != userId && (!m.IsMuted || mentions.Contains(m.UserId)) && !presence.IsOnline(m.UserId))
                .Select(m => m.UserId).ToList();
            if (offline.Count > 0)
            {
                var title = c.Type == ConversationType.Group ? $"{mineDto.SenderName} in {c.Name}" : mineDto.SenderName;
                await push.SendAsync(offline, new PushMessage(title, ModerationRules.Preview(decision.Text, 120),
                    new Dictionary<string, string> { ["type"] = "chat", ["conversationId"] = conversationId.ToString() }), ct);
            }
        }
        catch (Exception ex)
        {
            logger.LogWarning(ex, "Delivering message {MessageId} in real time failed; clients will load it", message.Id);
        }
        return mineDto;
    }

    public async Task<Result> DeleteMessageAsync(Guid userId, long messageId, bool forEveryone, CancellationToken ct = default)
    {
        var message = await db.Messages.FirstOrDefaultAsync(m => m.Id == messageId, ct);
        if (message is null) return Error.NotFound("Message");
        var member = await MemberAsync(userId, message.ConversationId, ct);
        if (member is null) return Error.NotFound("Message");

        if (!forEveryone)
        {
            var state = await db.MessageRecipientStates.FirstOrDefaultAsync(s => s.MessageId == messageId && s.UserId == userId, ct);
            if (state is null) db.MessageRecipientStates.Add(new MessageRecipientState { MessageId = messageId, UserId = userId, IsActive = false });
            else state.IsActive = false;
            await db.SaveChangesAsync(ct);
            return Result.Success();
        }

        // FR-C11: the sender within the time limit; group owners and admins any time.
        var isAdmin = member.Role is MemberRole.Admin or MemberRole.Owner;
        if (message.SenderId != userId && !isAdmin) return Error.Forbidden("not_your_message", "You can only delete your own messages for everyone.");
        if (message.SenderId == userId && !isAdmin)
        {
            var hours = await settings.GetIntAsync(SettingKeys.ChatDeleteForEveryoneHours, 24, ct);
            if (!ModerationRules.CanDeleteForEveryone(message.SentAt, clock.GetUtcNow(), hours))
                return Error.Conflict("delete_window_passed", $"Messages can be deleted for everyone within {hours} hours.");
        }
        if (!message.IsActive) return Result.Success();

        message.IsActive = false;
        message.DeletedForEveryoneAt = clock.GetUtcNow();
        message.DeletedBy = userId;
        await db.SaveChangesAsync(ct);
        await notifier.MessageDeletedAsync(await MemberIdsAsync(message.ConversationId, ct), new MessageDeletedDto(message.ConversationId, messageId), ct);
        return Result.Success();
    }

    public async Task<Result> ReactAsync(Guid userId, long messageId, string? emoji, CancellationToken ct = default)
    {
        var message = await db.Messages.AsNoTracking().Where(m => m.Id == messageId).Select(m => new { m.ConversationId, m.IsActive, m.MessageType })
            .FirstOrDefaultAsync(ct);
        if (message is null || await MemberAsync(userId, message.ConversationId, ct) is null) return Error.NotFound("Message");
        if (!message.IsActive || message.MessageType == MessageType.System) return Error.Validation("Emoji", "You can't react to this message.");

        var existing = await db.MessageReactions.FirstOrDefaultAsync(r => r.MessageId == messageId && r.UserId == userId, ct);
        if (string.IsNullOrWhiteSpace(emoji))
        {
            if (existing is not null) db.MessageReactions.Remove(existing);
        }
        else
        {
            if (!Emojis.Contains(emoji)) return Error.Validation("Emoji", "Pick one of the reactions.");
            if (existing is null) db.MessageReactions.Add(new MessageReaction { MessageId = messageId, UserId = userId, Emoji = emoji, CreatedAt = clock.GetUtcNow() });
            else existing.Emoji = emoji;
        }
        await db.SaveChangesAsync(ct);
        var dto = (await ToDtosAsync(userId, [messageId], ct))[0];
