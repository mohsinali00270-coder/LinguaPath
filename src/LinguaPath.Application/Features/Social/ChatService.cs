    public async Task<IReadOnlyList<ConversationSummaryDto>> ConversationsAsync(Guid userId, bool archived, CancellationToken ct = default)
    {
        var mine = await db.ConversationMembers.AsNoTracking()
            .Where(m => m.UserId == userId && m.IsActive && !m.IsPending && m.IsArchived == archived && m.Conversation.IsActive)
            .Select(m => new
            {
                m.ConversationId, m.Conversation.Type, m.Conversation.Name, m.Conversation.IconKey, m.Conversation.LastMessageId,
                m.Conversation.LastMessageAt, m.Conversation.CreatedAt, m.IsMuted, m.IsArchived, m.LastReadMessageId, m.ClearedBeforeMessageId
            })
            .ToListAsync(ct);
        if (mine.Count == 0) return [];

        var ids = mine.Select(m => m.ConversationId).ToList();
        var others = await db.ConversationMembers.AsNoTracking()
            .Where(m => ids.Contains(m.ConversationId) && m.Conversation.Type == ConversationType.Direct && m.UserId != userId)
            .Select(m => new { m.ConversationId, m.UserId, Name = m.User.DisplayName ?? m.User.FullName, m.User.PhotoUrl, m.User.IsBlocked })
            .ToListAsync(ct);
        var lastIds = mine.Where(m => m.LastMessageId != null).Select(m => m.LastMessageId!.Value).ToList();
        var lasts = await db.Messages.AsNoTracking().Where(m => lastIds.Contains(m.Id))
            .Select(m => new { m.Id, m.Body, m.IsActive, m.SenderId, m.MessageType, SenderName = m.Sender == null ? null : m.Sender.DisplayName ?? m.Sender.FullName })
            .ToDictionaryAsync(m => m.Id, ct);
        var hiddenForMe = (await db.MessageRecipientStates.AsNoTracking()
            .Where(s => s.UserId == userId && !s.IsActive && lastIds.Contains(s.MessageId)).Select(s => s.MessageId).ToListAsync(ct)).ToHashSet();
        var unread = await db.Messages.AsNoTracking()
            .Where(m => ids.Contains(m.ConversationId) && m.IsActive && m.SenderId != userId && m.SenderId != null)
            .Join(db.ConversationMembers.Where(cm => cm.UserId == userId), m => m.ConversationId, cm => cm.ConversationId, (m, cm) => new { m, cm })
            .Where(x => (x.cm.LastReadMessageId == null || x.m.Id > x.cm.LastReadMessageId) && x.m.SentAt >= x.cm.JoinedAt)
            .GroupBy(x => x.m.ConversationId).Select(g => new { g.Key, Count = g.Count() })
            .ToDictionaryAsync(x => x.Key, x => x.Count, ct);

        return mine.Select(m =>
            {
                var other = others.FirstOrDefault(o => o.ConversationId == m.ConversationId);
                string? preview = null;
                if (m.LastMessageId is { } lastId && lasts.TryGetValue(lastId, out var last) && lastId > (m.ClearedBeforeMessageId ?? 0))
                {
                    preview = !last.IsActive || hiddenForMe.Contains(lastId) ? "Message deleted"
                        : last.MessageType is MessageType.System or MessageType.CompetitionCard ? last.Body
                        : (m.Type == ConversationType.Group && last.SenderId != userId ? $"{last.SenderName}: " : last.SenderId == userId ? "You: " : "")
                          + ModerationRules.Preview(last.Body, 60);
                }
                var showOnline = other is not null && !other.IsBlocked;
                return new ConversationSummaryDto(m.ConversationId, m.Type,
                    m.Type == ConversationType.Direct ? (other?.IsBlocked == true ? "Blocked account" : other?.Name ?? "Learner") : m.Name ?? "Group",
                    m.Type == ConversationType.Direct && other?.IsBlocked != true ? other?.PhotoUrl : null, m.IconKey,
                    preview, m.LastMessageAt ?? m.CreatedAt, unread.GetValueOrDefault(m.ConversationId), m.IsMuted, m.IsArchived,
                    other?.UserId, showOnline ? presence.IsOnline(other!.UserId) : null);
            })
            .OrderByDescending(c => c.LastMessageAt)
            .ToList();
    }

    public async Task<Result<ConversationDto>> GetAsync(Guid userId, int conversationId, CancellationToken ct = default)
    {
        var member = await MemberAsync(userId, conversationId, ct);
        if (member is null)
        {
            // Public groups can be previewed before joining.
            var isPublic = await db.Conversations.AnyAsync(c => c.Id == conversationId && c.IsActive && c.IsPublic, ct);
            if (!isPublic) return Error.NotFound("Chat");
        }
        return await BuildAsync(userId, conversationId, ct);
    }

    public async Task<Result<ConversationDto>> OpenDirectAsync(Guid userId, Guid otherId, CancellationToken ct = default)
    {
        var key = ModerationRules.DirectKey(userId, otherId);
        var existing = await db.Conversations.AsNoTracking().Where(c => c.DirectKey == key).Select(c => (int?)c.Id).FirstOrDefaultAsync(ct);
        if (existing is { } id)
        {
            // Re-opening an old chat is always allowed; sending is checked per message.
            var me = await db.ConversationMembers.FirstOrDefaultAsync(m => m.ConversationId == id && m.UserId == userId, ct);
            if (me is not null && me.IsArchived)
            {
                me.IsArchived = false;
                await db.SaveChangesAsync(ct);
            }
            return await BuildAsync(userId, id, ct);
        }

        var allowed = await social.CanContactAsync(userId, otherId, false, ct);
        if (allowed.IsFailure) return allowed.Error!;
        var restriction = await moderation.ChatRestrictionAsync(userId, ct);
        if (restriction is { Blocked: true } or { Code: "chat_suspended" }) return Error.Conflict(restriction.Code, restriction.Message);

        var now = clock.GetUtcNow();
        var conversation = new Conversation { Type = ConversationType.Direct, DirectKey = key, CreatedBy = userId, CreatedAt = now };
        conversation.Members.Add(new ConversationMember { UserId = userId, Role = MemberRole.Member, JoinedAt = now });
        conversation.Members.Add(new ConversationMember { UserId = otherId, Role = MemberRole.Member, JoinedAt = now });
        db.Conversations.Add(conversation);
        try
        {
            await db.SaveChangesAsync(ct);
        }
        catch (DbUpdateException)
        {
            // Both learners opened the chat at the same moment: use the one that won.
            var winner = await db.Conversations.AsNoTracking().Where(c => c.DirectKey == key).Select(c => c.Id).FirstAsync(ct);
            return await BuildAsync(userId, winner, ct);
        }
        return await BuildAsync(userId, conversation.Id, ct);
    }

    public async Task<Result<ConversationDto>> CreateGroupAsync(Guid userId, CreateGroupRequest request, CancellationToken ct = default)
    {
        var name = request.Name?.Trim() ?? "";
        if (name.Length is < 2 or > 80) return Error.Validation("Name", "Group names are 2 to 80 characters.");
        if (request.Description is { Length: > 500 }) return Error.Validation("Description", "Keep the description under 500 characters.");
        var restriction = await moderation.ChatRestrictionAsync(userId, ct);
        if (restriction is not null) return Error.Conflict(restriction.Code, restriction.Message);
        var check = await moderation.CheckTextAsync(userId, ModerationTarget.GroupName, $"{name}\n{request.Description}", ct);
        if (check.IsFailure) return check.Error!;
        if (request.LanguageId is { } lang && !await db.Languages.AnyAsync(l => l.Id == lang, ct)) return Error.Validation("LanguageId", "Unknown language.");

        var maxGroups = await settings.GetIntAsync(SettingKeys.ChatMaxGroupsPerUser, 10, ct);
        var owned = await db.ConversationMembers.CountAsync(m => m.UserId == userId && m.IsActive && m.Role == MemberRole.Owner
                                                                 && m.Conversation.Type == ConversationType.Group && m.Conversation.IsActive, ct);
        if (maxGroups > 0 && owned >= maxGroups) return Error.Conflict("group_limit", $"You can own up to {maxGroups} groups.");

        var maxMembers = await settings.GetIntAsync(SettingKeys.ChatGroupMaxMembers, 100, ct);
        var invite = (request.MemberIds ?? []).Where(id => id != userId).Distinct().ToList();
        if (invite.Count + 1 > maxMembers) return Error.Validation("MemberIds", $"Groups can have up to {maxMembers} members.");
        foreach (var id in invite)
        {
            var ok = await social.CanContactAsync(userId, id, false, ct);
            if (ok.IsFailure) return Error.Validation("MemberIds", "Some of these learners can't be added: " + ok.Error!.Message);
        }

        var now = clock.GetUtcNow();
        var group = new Conversation
        {
            Type = ConversationType.Group, Name = name, Description = request.Description?.Trim(), IconKey = Icon(request.IconKey),
            LanguageId = request.LanguageId, IsPublic = request.IsPublic, CreatedBy = userId, CreatedAt = now
        };
        group.Members.Add(new ConversationMember { UserId = userId, Role = MemberRole.Owner, JoinedAt = now });
        foreach (var id in invite) group.Members.Add(new ConversationMember { UserId = id, Role = MemberRole.Member, JoinedAt = now });
        db.Conversations.Add(group);
        await db.SaveChangesAsync(ct);

        await SystemMessageAsync(group.Id, $"{await NameAsync(userId, ct)} created the group \"{name}\"", ct);
        return await BuildAsync(userId, group.Id, ct);
    }

    public async Task<Result<ConversationDto>> UpdateAsync(Guid userId, int conversationId, UpdateConversationRequest r, CancellationToken ct = default)
    {
        var member = await db.ConversationMembers.Include(m => m.Conversation)
            .FirstOrDefaultAsync(m => m.ConversationId == conversationId && m.UserId == userId && m.IsActive && !m.IsPending, ct);
        if (member is null) return Error.NotFound("Chat");

        if (r.Muted is { } muted) member.IsMuted = muted;
        if (r.Archived is { } archived) member.IsArchived = archived;

        var c = member.Conversation;
        var settingsChange = r.Name is not null || r.Description is not null || r.IconKey is not null || r.LanguageId is not null || r.IsPublic is not null
                             || r.OnlyAdminsCanSend is not null || r.SlowModeSec is not null || r.JoinApproval is not null;
        var changes = new List<string>();
        if (settingsChange)
        {
            if (c.Type != ConversationType.Group) return Error.Validation("Name", "Only groups have settings.");
            if (member.Role == MemberRole.Member) return Error.Forbidden("not_group_admin", "Only the owner and admins can change the group.");
            if (r.Name is not null)
            {
                var name = r.Name.Trim();
                if (name.Length is < 2 or > 80) return Error.Validation("Name", "Group names are 2 to 80 characters.");
                var check = await moderation.CheckTextAsync(userId, ModerationTarget.GroupName, name, ct);
                if (check.IsFailure) return check.Error!;
                if (name != c.Name) changes.Add($"renamed the group to \"{name}\"");
                c.Name = name;
            }
            if (r.Description is not null)
            {
                if (r.Description.Length > 500) return Error.Validation("Description", "Keep the description under 500 characters.");
                var check = await moderation.CheckTextAsync(userId, ModerationTarget.GroupName, r.Description, ct);
                if (check.IsFailure) return check.Error!;
                c.Description = r.Description.Trim();
            }
            if (r.IconKey is not null) c.IconKey = Icon(r.IconKey);
            if (r.LanguageId is { } lang) c.LanguageId = lang <= 0 ? null : lang;
            if (r.IsPublic is { } pub) c.IsPublic = pub;
            if (r.OnlyAdminsCanSend is { } only && only != c.OnlyAdminsCanSend)
            {
                c.OnlyAdminsCanSend = only;
                changes.Add(only ? "turned on announcement mode" : "let everyone send messages");
            }
            if (r.SlowModeSec is { } slow)
            {
                if (slow is < 0 or > 3600) return Error.Validation("SlowModeSec", "Slow mode is 0 to 3,600 seconds.");
                if (slow != c.SlowModeSec) changes.Add(slow == 0 ? "turned off slow mode" : $"set slow mode to {slow} seconds");
                c.SlowModeSec = slow;
            }
            if (r.JoinApproval is { } approval) c.JoinApproval = approval;
        }
        await db.SaveChangesAsync(ct);

        if (changes.Count > 0)
        {
            var who = await NameAsync(userId, ct);
            foreach (var change in changes) await SystemMessageAsync(conversationId, $"{who} {change}", ct);
            await notifier.ConversationChangedAsync(await MemberIdsAsync(conversationId, ct), new ConversationChangedDto(conversationId, "settings"), ct);
        }
        return await BuildAsync(userId, conversationId, ct);
    }

