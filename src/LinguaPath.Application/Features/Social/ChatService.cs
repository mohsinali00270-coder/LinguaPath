/// <summary>1:1 and group chat (FR-C01 .. FR-C32). Real-time delivery goes through <see cref="IChatNotifier"/>.</summary>
public interface IChatService
{
    Task<IReadOnlyList<ConversationSummaryDto>> ConversationsAsync(Guid userId, bool archived, CancellationToken ct = default);
    Task<Result<ConversationDto>> GetAsync(Guid userId, int conversationId, CancellationToken ct = default);
    Task<Result<ConversationDto>> OpenDirectAsync(Guid userId, Guid otherId, CancellationToken ct = default);
    Task<Result<ConversationDto>> CreateGroupAsync(Guid userId, CreateGroupRequest request, CancellationToken ct = default);
    Task<Result<ConversationDto>> UpdateAsync(Guid userId, int conversationId, UpdateConversationRequest request, CancellationToken ct = default);

    Task<Result<IReadOnlyList<MessageDto>>> MessagesAsync(Guid userId, int conversationId, long? before, int take, CancellationToken ct = default);
    Task<Result<MessageDto>> SendAsync(Guid userId, int conversationId, SendMessageRequest request, CancellationToken ct = default);
    Task<Result> DeleteMessageAsync(Guid userId, long messageId, bool forEveryone, CancellationToken ct = default);
    Task<Result> ReactAsync(Guid userId, long messageId, string? emoji, CancellationToken ct = default);
    Task<Result<SeenDto>> MarkSeenAsync(Guid userId, int conversationId, long upToMessageId, CancellationToken ct = default);
    /// <summary>On connect: everything waiting for me is now delivered (FR-C03). Returns the chats whose senders should hear about it.</summary>
    Task MarkDeliveredAsync(Guid userId, CancellationToken ct = default);
    Task<Result<IReadOnlyList<SeenByDto>>> SeenByAsync(Guid userId, long messageId, CancellationToken ct = default);
    Task<Result> ClearAsync(Guid userId, int conversationId, CancellationToken ct = default);
    Task<Result<TranslatedMessageDto>> TranslateAsync(Guid userId, long messageId, string? to, CancellationToken ct = default);
    Task<IReadOnlyList<MessageSearchHitDto>> SearchAsync(Guid userId, string query, CancellationToken ct = default);

    Task<IReadOnlyList<PublicGroupDto>> PublicGroupsAsync(Guid userId, string? query, int? languageId, CancellationToken ct = default);
    Task<Result<ConversationDto>> JoinAsync(Guid userId, int conversationId, CancellationToken ct = default);
    Task<Result> AddMembersAsync(Guid userId, int conversationId, IReadOnlyList<Guid> memberIds, CancellationToken ct = default);
    Task<Result> RemoveMemberAsync(Guid userId, int conversationId, Guid memberId, CancellationToken ct = default);
    Task<Result> ApproveAsync(Guid userId, int conversationId, Guid memberId, bool approve, CancellationToken ct = default);
    Task<Result> ChangeRoleAsync(Guid userId, int conversationId, Guid memberId, MemberRole role, CancellationToken ct = default);
    Task<Result> LeaveAsync(Guid userId, int conversationId, CancellationToken ct = default);

    /// <summary>
    /// Phase 9: a competition card (invitation or result) posted by a member (FR-Q07, FR-C28). The text is generated by the server,
    /// so it skips the word filter, but announcement mode, privacy and blocks still apply.
    /// </summary>
    Task<Result<MessageDto>> PostCompetitionCardAsync(Guid userId, int conversationId, int competitionId, string text, CancellationToken ct = default);

    /// <summary>Hub helpers.</summary>
    Task<IReadOnlyList<Guid>> MemberIdsAsync(int conversationId, CancellationToken ct = default);
    Task<bool> IsMemberAsync(Guid userId, int conversationId, CancellationToken ct = default);
}

